"""Write templates/agora-desk.template.yaml: the rooms from templates/desk.rooms.yaml plus the two
agents Switch Console creates (Claude Code builder, OpenCode reviewer). `--check` fails if it's stale.
Standard library only: the rooms file is copied as text, the agents block is prepended."""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ROOMS = (ROOT / "templates/desk.rooms.yaml").read_text()
OUT = ROOT / "templates/agora-desk.template.yaml"

AGENTS = '''agents:
  - name: "{builder}"
    display_name: Builder
    description: Fixes work orders in acme-invoices and reports to the Notary with a claims block
    provider: claude
    location: "{location}"
    directory: "{directory}"
    repo: https://github.com/Ritesh-Root/acme-invoices
    addressing: owner-agents
    instructions: |
      You are the builder on this desk. You work only in the work room, and only on
      work orders the Notary gives you. For each one:
      1. Read the work order's room document and the Desk Policy and Reporting Contract documents.
      2. Fix it in the acme-invoices folder in your directory, on the branch the work order names,
         starting from the base it names. Don't edit the files the Desk Policy protects;
         put new tests in new files.
      3. Run the full test suite as one plain command: pytest -q
      4. Commit, push the branch, and report to the Notary in the work room. End your
         message with one notary-claims block: commit_pushed, files_changed (every path
         you changed or added), tests_passed, check_ran. Use the full 40-character sha.
      Claim only what you ran or saw. If the Notary bounces your report, fix what its
      codes say and report again.
  - name: "{reviewer}"
    display_name: Reviewer
    description: Reviews the builder's change at the reported commit and reports to the Notary
    provider: opencode
    location: "{location}"
    directory: "{directory}"
    repo: https://github.com/Ritesh-Root/acme-invoices
    addressing: owner-agents
    instructions: |
      You are the reviewer on this desk. When the Notary asks you to review a work
      order: fetch the branch it names in the acme-invoices folder in your directory,
      run git diff main...<sha> to read the change, and run the full suite as one plain
      command: pytest -q. Then report to the Notary in the work room with one
      notary-claims block: reviewed_diff (the sha) and check_ran (the command and
      whether it passed). Say plainly if you think the change is wrong.
'''

PARAMS_EXTRA = '''  location:
    type: location
    default: local
    input: advanced
  directory:
    type: directory
    description: Each agent's own working folder
    default: "{$agents_dir}/{agent}"
    input: advanced
'''

KICKOFF = '''    kickoff: |
      @{builder} @{reviewer} this is the {team} work room. Say hello in one line, then read
      the Desk Policy and Reporting Contract documents. Wait for work orders from the Notary.
'''


def build():
    head, rest = ROOMS.split("group:\n", 1)
    head = head.replace("# scripts/install.sh posts this to /gateway/rooms/from-yaml for the keyless demo; the Console\n# template (agora-desk.template.yaml) creates the same rooms together with the Claude Code and\n# OpenCode agents.\n",
                        "# GENERATED by scripts/console-template.py from desk.rooms.yaml: apply it in Switch Console.\n")
    head += PARAMS_EXTRA
    rest = rest.replace("    docs:\n", KICKOFF + "    docs:\n", 1)
    return head + AGENTS + "group:\n" + rest


text = build()
if "--check" in sys.argv:
    sys.exit(0 if OUT.exists() and OUT.read_text() == text else "templates/agora-desk.template.yaml is stale: run python3 -I scripts/console-template.py")
OUT.write_text(text)
print(f"wrote {OUT.relative_to(ROOT)}")
